/**
 * Правило расписания — единственное место, где задано, как календарь
 * превращается в слоты. Всё остальное только читает эти значения.
 *
 * Слот — это получасовой интервал окна приёма, который занимается целиком.
 * Окно 09:00–18:00 при шаге 30 минут даёт 18 слотов, последний — 17:30–18:00.
 */

/** Таймзона организатора: в ней задано правило и показываются все слоты. */
export const organizerTimeZone = 'Europe/Moscow'

/** Начало окна приёма, минуты от полуночи в таймзоне организатора. */
export const dayStartMinutes = 9 * 60

/** Конец окна приёма, минуты от полуночи в таймзоне организатора. */
export const dayEndMinutes = 18 * 60

/** Длительность слота, минуты. */
export const slotDurationMinutes = 30

/** Горизонт записи: сколько дней вперёд от сегодня можно забронировать. */
export const horizonDays = 30

/** Насколько далеко назад можно листать календарь, месяцев. */
export const backMonths = 3

/**
 * Число слотов в полном дне. Считается, а не записано числом: «18» должно
 * меняться само, если поменять окно или шаг.
 */
export const slotsPerDay =
  (dayEndMinutes - dayStartMinutes) / slotDurationMinutes