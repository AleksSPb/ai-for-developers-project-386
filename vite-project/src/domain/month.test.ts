import { describe, expect, it } from 'vitest'
import { getMonthCells, getMonthTitleRange } from '../domain/month'
import type { MonthKey } from '../domain/calendar'

/**
 * Сетка месяца и заголовок.
 *
 * Два требования, которые легко спутать: обрезанные места закрываются заглушками
 * **без чисел**, а заголовок несёт диапазон дат **всегда**, в том числе в полном
 * месяце. Иначе подписью «ноябрь» приходилось бы гадать, где кончается
 * доступное.
 */

describe('сетка месяца', () => {
  /** Месяц показан целиком: слева 1-е, справа 31-е. */
  const full = getMonthCells('2026-10', '2026-10-01', '2026-10-31')
  /** Месяц обрезан: сегодня 20-е, последний день со Слотом — 22-е. */
  const trimmed = getMonthCells('2026-10', '2026-10-20', '2026-10-22')

  it('начинается с понедельника', () => {
    // 1 октября 2026 — четверг, значит перед ним три пустых места.
    expect(full.slice(0, 3)).toEqual([null, null, null])
    expect(full[3]).toBe('2026-10-01')
  })

  it('заканчивается последним днём месяца', () => {
    const drawn = full.filter((cell): cell is string => cell !== null)
    expect(drawn.at(-1)).toBe('2026-10-31')
  })

  it('не рисует ни одного дня раньше сегодняшнего', () => {
    const drawn = trimmed.filter((cell): cell is string => cell !== null)
    expect(drawn.some((date) => date < '2026-10-20')).toBe(false)
  })

  it('за последним Слотом стоят заглушки без чисел', () => {
    const drawn = trimmed.filter((cell): cell is string => cell !== null)

    expect(drawn).toEqual(['2026-10-20', '2026-10-21', '2026-10-22'])
    // Ячейок больше, чем дней: недельные отступы и обрезанные дни — заглушки.
    expect(trimmed).toHaveLength(35)
  })

  it('не рисует ни одного дня позже последнего дня со Слотом', () => {
    const drawn = trimmed.filter((cell): cell is string => cell !== null)
    expect(drawn.some((date) => date > '2026-10-22')).toBe(false)
  })

  it('сетка всегда полной недели, иначе строки разной длины', () => {
    expect(full.length % 7).toBe(0)
    expect(trimmed.length % 7).toBe(0)
  })
})

describe('заголовок месяца', () => {
  it('несёт диапазон дат в полном месяце', () => {
    expect(getMonthTitleRange('2026-10-01', '2026-10-31', '2026-10')).toBe('1 – 31 октября 2026')
  })

  it('несёт диапазон и в обрезанном месяце', () => {
    expect(getMonthTitleRange('2026-10-20', '2026-10-22', '2026-10')).toBe('20 – 22 октября 2026')
  })

  it('обрезанный слева месяц начинается с сегодняшнего дня', () => {
    expect(getMonthTitleRange('2026-10-28', '2026-10-31', '2026-10')).toBe('28 – 31 октября 2026')
  })

  it('одиночный день даёт один и тот же день дважды', () => {
    // Диапазон из одного дня читается как «31 – 31», и это честнее, чем молча
    // прятать вторую границу.
    expect(getMonthTitleRange('2026-10-22', '2026-10-22', '2026-10')).toBe('22 – 22 октября 2026')
  })

  it('название месяца склоняется как требует русский язык', () => {
    const titles: string[] = (['2026-01', '2026-02', '2026-03', '2026-04', '2026-05', '2026-06'] as MonthKey[]).map(
      (month) => getMonthTitleRange(month + '-01', month + '-28', month),
    )

    expect(titles).toEqual([
      '1 – 28 января 2026',
      '1 – 28 февраля 2026',
      '1 – 28 марта 2026',
      '1 – 28 апреля 2026',
      '1 – 28 мая 2026',
      '1 – 28 июня 2026',
    ])
  })
})