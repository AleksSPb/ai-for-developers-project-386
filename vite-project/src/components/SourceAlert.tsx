import { Alert } from '@mantine/core'

interface SourceAlertProps {
  message: string
}

/**
 * Отказ источника.
 *
 * Один компонент на гостевую страницу и раздел Владельца: отказ должен выглядеть
 * одинаково везде, иначе Гость решит, что сломался только его раздел.
 *
 * Отказ **убирает** всё, что было показано раньше: ранее загруженная карточка
 * рядом с красной плашкой читалась бы как «данные показаны, но с оговоркой», а
 * на самом деле их не узнали.
 */
const SourceAlert = ({ message }: SourceAlertProps) => (
  <Alert color="red" title="Не удалось загрузить расписание">
    {message}
  </Alert>
)

export default SourceAlert