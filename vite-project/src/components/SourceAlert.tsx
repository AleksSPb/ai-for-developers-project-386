import { Alert, Button, Stack, Text } from '@mantine/core'

import { SOURCE_FAILURE_TEXT } from '../app/sourceText'
import { useApp } from '../app/useApp'

/**
 * Отказ источника.
 *
 * Один компонент на гостевую страницу и раздел Владельца: отказ должен выглядеть
 * одинаково везде, иначе Гость решит, что сломался только его экран.
 *
 * Текст свой, а не `message` из ответа: то поле — строка для разработчика, и на
 * первом же отказе она оказалась бы перед гостем.
 *
 * Отказ **убирает** всё, что было показано раньше: ранее загруженная карточка
 * рядом с красной плашкой читалась бы как «данные показаны, но с оговоркой», а на
 * самом деле их не узнали. Устаревшая строка без пометки хуже отсутствия строки:
 * она выглядит актуальной, и Владелец принял бы решение по данным минутной
 * давности, не зная об этом.
 *
 * Кнопка повтора одна и зовёт приложение: она перечитывает все источники страницы,
 * а не тот, который виноват в отказе.
 */
const SourceAlert = () => {
  const { retryAll } = useApp()

  return (
    <Alert color="red" title="Не удалось загрузить расписание">
      <Stack gap="sm">
        <Text size="sm">{SOURCE_FAILURE_TEXT}</Text>
        <Button variant="default" size="xs" onClick={retryAll}>
          Повторить
        </Button>
      </Stack>
    </Alert>
  )
}

export default SourceAlert