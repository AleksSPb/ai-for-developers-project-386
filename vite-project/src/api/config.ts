/**
 * Адрес сервера.
 *
 * Имя переменной объявлено здесь один раз и проверяется компилятором: опечатка
 * в `import.meta.env.VITE_API_BASE_URL` не склеивается с путём запроса, а
 * падает на сборке. Без явного объявления `ImportMetaEnv` любой набор букв был
 * бы допустимым именем и дал бы `undefined` вместо адреса.
 */
interface ServerAddress {
  VITE_API_BASE_URL: string
}

const env = import.meta.env as unknown as Partial<ServerAddress>

/**
 * Адрес, к которому ходит клиент.
 *
 * Переопределяется переменной окружения: `VITE_API_BASE_URL=http://localhost:8080`.
 * Без неё адрес пустой, и запрос уходит в корень собственного origin — то есть
 * в статическую раздачу, которая ответила бы пустотой вместо данных.
 */
export const baseUrl: string = env.VITE_API_BASE_URL ?? ''

/**
 * Отвечает ли заглушка вместо сервера.
 *
 * Решение принимает наличие адреса, а не отдельный флаг: адрес задан — значит
 * сервер есть и заглушка была бы ложью поверх его ответов. Явный флаг в
 * `.env` разошёлся бы с адресом, и заглушка осталась бы включённой там, где
 * сервер есть.
 */
export const usesStubs: boolean = env.VITE_API_BASE_URL === undefined