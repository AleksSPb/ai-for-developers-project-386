import { afterEach, describe, expect, it, vi } from 'vitest'

/**
 * Адрес сервера.
 *
 * Ценность теста не в значении, а в том, что имя переменной окружения объявлено:
 * без объявления опечатка в имени молча дала бы `undefined`, и запрос ушёл бы в
 * корень собственного origin — то есть в статическую раздачу, которая ответила бы
 * пустотой вместо данных.
 *
 * Переменная окружения **подставляется тестом**, а не берётся из машины: файл
 * `vite-project/.env.local` нужен, чтобы вести разработку против живого сервера,
 * и Vitest читает его так же, как Vite. Тест, полагавшийся на отсутствие адреса
 * в окружении, падал бы у того, кто адрес задал, — то есть проверял бы не
 * поведение модуля, а обстановку вокруг него.
 */
describe('адрес сервера', () => {
  afterEach(() => {
    vi.unstubAllEnvs()
    vi.resetModules()
  })

  /** Перечитывает модуль с подставленной переменной окружения. */
  const withAddress = async (address: string | undefined) => {
    vi.stubEnv('VITE_API_BASE_URL', address as string)
    vi.resetModules()

    return import('./config')
  }

  it('без переменной окружения включает заглушки и не выдумывает адрес', async () => {
    // Тесты ходят по заглушкам всегда: заданный адрес должен уводить их в сеть,
    // к серверу, которого на машине может не быть.
    const { baseUrl, usesStubs } = await withAddress(undefined)

    expect(usesStubs).toBe(true)
    expect(baseUrl).toBe('')
  })

  it('с адресом заглушки не поднимает, а адрес достаётся как есть', async () => {
    const { baseUrl, usesStubs } = await withAddress('http://localhost:8080')

    // Обратное к предыдущему: заглушка поверх ответов настоящего сервера была бы
    // ложью, поэтому решает наличие адреса, а не отдельный флаг.
    expect(usesStubs).toBe(false)
    // Путь приклеивается конкатенацией, поэтому пробелы и слэш на конце испортили
    // бы адрес молча, а не с ошибкой: адрес достаётся тем, чем его задали.
    expect(baseUrl).toBe('http://localhost:8080')
  })
})