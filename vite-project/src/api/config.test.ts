import { describe, expect, it } from 'vitest'
import { baseUrl, usesStubs } from './config'

/**
 * Адрес сервера.
 *
 * Ценность теста не в значении, а в том, что имя переменной окружения
 * объявлено: без объявления опечатка в имени молча дала бы `undefined`, и запрос
 * ушёл бы в корень собственного origin — то есть в статическую раздачу, которая
 * ответила бы пустотой вместо данных.
 */
describe('адрес сервера', () => {
  it('без переменной окружения включает заглушки и не выдумывает адрес', () => {
    // Переменная в тестах не задана, поэтому тесты ходят по заглушкам, а не по
    // адресу: иначе они звали бы сервер, которого на машине может не быть.
    expect(usesStubs).toBe(true)
  })

  it('адрес склеивается с путём запроса как есть', () => {
    // Путь приклеивается конкатенацией, поэтому пробелы и слэш на конце
    // испортили бы адрес молча, а не с ошибкой.
    expect(baseUrl).toBe(baseUrl.trim())
    expect(baseUrl.endsWith('/')).toBe(false)
  })
})