/**
 * Пределы текстов Типа события на стороне интерфейса.
 *
 * Источник правды — контракт: `maxLength` в `main.tsp`. Здесь те же числа, потому
 * что форма должна отказывать в лишнем **до** отправки, а не после: длинное
 * название попадает в гостевую ссылку, а исправить его после создания нельзя —
 * удаления Типа и смены идентификатора нет, только завести новый Тип и раздать
 * новые ссылки.
 *
 * Расхождение с контрактом ловит тест `contract.test.ts`: он читает
 * `openapi.yaml` и сверяет с этим объектом. Правило одно — проверка есть и там, и
 * тут, а не в одном из двух мест.
 *
 * Числа **разные и в строгом порядке**: идентификатор короче названия, название
 * короче описания. Одинаковый предел означал бы, что границы придуманы из
 * удобства, а не из того, что идентификатор попадает прямо в адрес, а описание —
 * единственное, чем два одинаково названных Типа различаются для Гостя.
 */
export const TEXT_LIMITS = {
  /** Попадает прямо в адрес и в ссылку, которую отправляют в чат. */
  id: 40,
  /** Короткая метка для показа. */
  name: 100,
  /** Текст, различающий два одноимённых Типа. */
  description: 600,
} as const

/**
 * Нижние границы тех же полей.
 *
 * У идентификатора она выше единицы, и это договорённость о том, как читается
 * гостевой адрес: `/book/abc` читается, а `/book/a` — нет. Название и описание в
 * адрес не попадают и пишутся свободно, поэтому у них единица.
 *
 * Три символа — не техническое ограничение: `/book/a` работал бы ничуть не хуже.
 * Оно нужно, чтобы Владелец не заводил однобуквенные идентификаторы и не жался
 * об них потом.
 */
export const TEXT_MINIMUMS = {
  id: 3,
  name: 1,
  description: 1,
} as const

export type TextField = keyof typeof TEXT_LIMITS

/**
 * Образец идентификатора: строчные латинские буквы, цифры и дефис.
 *
 * Живёт здесь, а не в контракте и не в заглушке отдельно: правило одно, и три его
 * копии разошлись бы при первом же переименовании. Сверяется с `pattern` из
 * `openapi.yaml` тестом контракта.
 */
export const ID_PATTERN = /^[a-z0-9-]+$/

/**
 * Единица длины в текстах отказа.
 *
 * Форма одна для всех чисел, а не согласованная по правилам русского языка:
 * «3 символа» и «5 символов» в техническом сообщении читаются одинаково, и разница
 * форм ничего не сообщает Владельцу. Заодно текст короче.
 */
const symbol = (count: number): string => `${count} символов`

/**
 * Чем именно поле не подходит — или `null`, если поле в порядке.
 *
 * Сервер присылает в отказе **только имя поля**, без причины: «пусто»,
 * «слишком коротко» и «не по образцу» для него один и тот же код. Назвать причину
 * может тот, кто знает правила, а правила живут здесь — и сверяются с контрактом.
 *
 * Тексты именно такие: «Значение не подходит» не говорит Владельцу, что делать, а
 * он ничего и не менял, — отказ оказывается бесполезным.
 *
 * Порядок проверок = порядок правил в контракте: сначала пусто, потом длина,
 * потом образец. Первую сработавшую и называем — при нескольких сразу Владелец
 * исправит по одному за кругу.
 */
export const problemWith = (field: TextField, value: string): string | null => {
  if (value.trim().length === 0) {
    return 'Заполните это поле'
  }

  if (textLength(value) < TEXT_MINIMUMS[field]) {
    return `Введите не меньше ${symbol(TEXT_MINIMUMS[field])}`
  }

  if (textLength(value) > TEXT_LIMITS[field]) {
    return `Введите не больше ${symbol(TEXT_LIMITS[field])}`
  }

  if (field === 'id' && !ID_PATTERN.test(value)) {
    return 'Только строчные латинские буквы, цифры и дефис'
  }

  return null
}

/** Сколько символов ещё можно вставить в поле. */
export const remainingIn = (field: TextField, value: string): number =>
  TEXT_LIMITS[field] - textLength(value)

/**
 * Длина в символах, а не в байтах и не в кодовых единицах.
 *
 * Байты означали бы, что кириллическое название упирается в предел раньше
 * латинского, а это не то, что Владелец считает написал. Символ — единица, в
 * которой человек думает о длине; она же считается одинаково для всех языков.
 *
 * Считается **точками кода**, а не `String.length`. У эмодзи и редких иероглифов вне
 * базовой плоскости `length` стоит два, и предел, обещанный контрактом, оказался бы
 * вдвое ниже того, что показывает счётчик: Владелец дописал бы 60 эмодзи из сотни
 * разрешённых и увидел бы «Осталось символов: 40», которого набрать уже нельзя.
 * `maxLength` в контракте считается в точках кода, и мера одна на обоих концах —
 * форма, счётчик и сервер.
 */
export const textLength = (value: string): number => [...value].length

/** Влезает ли значение в предел поля. */
export const fitsIn = (field: TextField, value: string): boolean =>
  textLength(value) <= TEXT_LIMITS[field]

/**
 * Граница, которую отдаём полю в атрибуте `maxLength`.
 *
 * Браузер считает этот атрибут в кодовых единицах UTF-16, где один символ может
 * стоить два, и поставил бы предел ниже контрактного: эмодзи Владелец не дописал
 * бы до конца, хотя контракт их разрешает. Поэтому атрибут удвоен — точка кода
 * длиннее двух единиц не бывает, и любой годный текст в него влезает целиком.
 *
 * Настоящую границу держит форма, отказывая во вводе сверх `fitsIn`, а не
 * атрибут: обрезание отняло бы конец фразы молча.
 */
export const TYPED_LIMITS = {
  id: TEXT_LIMITS.id * 2,
  name: TEXT_LIMITS.name * 2,
  description: TEXT_LIMITS.description * 2,
} as const