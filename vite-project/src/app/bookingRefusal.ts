import type { bookingsCreateBookingResponse } from '../api/generated/calendar-api'

/**
 * Отказ при создании Брони.
 *
 * Код ответа и тело с ним — **ответ сервера**, а не отказ самого запроса:
 * генератор не бросает на 4xx и 5xx, а возвращает результат. Поэтому разбор идёт
 * ветвлением по статусу, а не `try/catch`: в `catch` попал бы и оборванный запрос,
 * а это другой случай с другим последствием для Гостя.
 *
 * Ни одно поле `message` из контракта в интерфейс не выводится: это строка для
 * разработчика, и на первом же неудачном запросе она оказалась бы перед Гостем.
 * Тексты принадлежат приложению и живут здесь.
 *
 * Формы Владельца разбирает соседний модуль `refusal.ts`: там отказ означает
 * «подсветить поле», здесь — «что теперь делать Гостю», и сводить их в один
 * разбор значило бы заставить один модуль знать про оба экрана.
 */
export type BookingRefusal =
  /** Слот занял кто-то другой. Введённые данные Гостя терять нельзя. */
  | { kind: 'занят' }
  /** Негодные поля: подсвечиваются сразу все. */
  | { kind: 'данные'; fields: string[] }
  /** Слота, который гость выбрал, больше нет: возвращаем к выбору дня. */
  | { kind: 'время' }
  /** Слот или Тип не найдены: возвращаем к выбору дня. */
  | { kind: 'нет такого' }
  /** Ответ сервера без тела, о котором он не предупредил: ничего не известно. */
  | { kind: 'недоступно' }

export type CreateOutcome =
  | { kind: 'создана' }
  | { kind: 'отказ'; refusal: BookingRefusal }

/**
 * Разбор ответа `POST /bookings`.
 *
 * Ветвление по статусу, сужение по коду — только там, где один код несёт **две
 * разные модели**: `422` это и «проверка не прошла», и «на это время записаться
 * нельзя», и подменять их одним разбором значило бы отправлять гостя искать
 * негодное поле интервала, которого на форме нет.
 *
 * Ответов, не описанных контрактом, здесь нет: значит и отдельного текста у них
 * нет — вместо него говорится «не получилось», потому что прочие коды неизвестны
 * и выдумывать о них причину значило бы врать.
 */
export const parseCreateResponse = (
  response: bookingsCreateBookingResponse,
): CreateOutcome => {
  if (response.status === 201) {
    return { kind: 'создана' }
  }

  if (response.status === 409) {
    return { kind: 'отказ', refusal: { kind: 'занят' } }
  }

  if (response.status === 422) {
    const { data } = response

    if (data.code === 'time_not_bookable') {
      return { kind: 'отказ', refusal: { kind: 'время' } }
    }

    return { kind: 'отказ', refusal: { kind: 'данные', fields: data.fields } }
  }

  if (response.status === 404) {
    return { kind: 'отказ', refusal: { kind: 'нет такого' } }
  }

  return { kind: 'отказ', refusal: { kind: 'недоступно' } }
}

/**
 * Можно ли ещё раз отправить эту же форму.
 *
 * После отказа по занятости — нельзя: Слот уже чужой, и гость получил бы тот же
 * отказ по кругу, потеряв введённое имя и почту второй раз. Остальные отказы дело
 * гостя — их исправление может снова дать успех.
 */
export const canRetry = (refusal: BookingRefusal): boolean => refusal.kind !== 'занят'

/**
 * Текст отказа для гостя.
 *
 * Тексты занятости, времени и негодных полей различаются намеренно: один общий
 * текст сказал бы гостю неправду — например, про «выбранное время» на негодном
 * имени, которое он только что ввёл и время которого было доступно.
 *
 * Тексты «время», «нет такого» и «недоступно» пока общие для своих пар и будут
 * разведены в #57 вместе с действиями гостя; здесь они только не совпадают между
 * собой и не совпадают с отказом по занятости.
 */
export const refusalText = (refusal: BookingRefusal): string => {
  switch (refusal.kind) {
    case 'занят':
      return 'Это время уже занял другой гость — выберите другое'
    case 'данные':
      return 'Проверьте имя и почту'
    case 'время':
      return 'Выбранное время больше недоступно'
    case 'нет такого':
      return 'Выбранное время больше недоступно'
    case 'недоступно':
      return 'Не получилось записаться. Попробуйте ещё раз'
  }
}