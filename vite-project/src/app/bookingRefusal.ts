import type { bookingsCreateBookingResponse } from '../api/generated/calendar-api'
import type { GuestErrors } from '../domain/booking'

/**
 * Отказ при создании Брони.
 *
 * Отказов два вида, и путать их дорого:
 *
 * - **Ответ сервера** — код и тело пришли, разбирать есть что.
 * - **Отказ запроса** — сеть оборвалась, тела не пришло вовсе.
 *
 * Разбор ответа идёт ветвлением по статусу, а не `try/catch`: в `catch` попал бы
 * и оборванный запрос, а это другой случай с другим последствием для Гостя.
 * `try/catch` стоит ровно в одном месте — вокруг самого запроса в `useBookings`.
 *
 * Ни одно поле `message` из контракта в интерфейс не выводится: это строка для
 * разработчика, и на первом же неудачном запросе она оказалась бы перед Гостем.
 * Тексты принадлежат приложению и живут здесь.
 *
 * Формы Владельца разбирает соседний модуль `refusal.ts`: там отказ означает
 * «подсветить поле», здесь — «что теперь делать Гостю», и сводить их в один
 * разбор значило бы заставить один модуль знать про оба экрана.
 */
export type BookingRefusal =
  /** Слот занял кто-то другой. Введённые данные Гостя терять нельзя. */
  | { kind: 'занят' }
  /**
   * Негодные поля записи.
   *
   * Имена полей — **формы**, а не контракта: `guestName` переводится в `name`
   * один раз, здесь же. Два словаря в одном поле означали бы, что подсветку
   * придётся угадывать по месту использования.
   */
  | { kind: 'данные'; fields: readonly GuestField[] }
  /** Слота, который гость выбрал, больше нет: возвращаем к выбору дня. */
  | { kind: 'время' }
  /** Слот или Тип не найдены: возвращаем к выбору дня. */
  | { kind: 'нет такого' }
  /** Ответ сервера о недоступности: причина известна, запись не создана. */
  | { kind: 'недоступно' }
  /** Оборвалась сеть: причина неизвестна, запись могла создаться. */
  | { kind: 'сеть' }

/** Поле формы Гостя — то, что подсвечивается под полем. */
export type GuestField = keyof GuestErrors

export type CreateOutcome =
  | { kind: 'создана' }
  | { kind: 'отказ'; refusal: BookingRefusal }

/**
 * Имена полей контракта в имена полей формы.
 *
 * Перевод живёт здесь, а не в разборе и не в компоненте: подсветка поля по названию
 * из контракта в двух местах разошлась бы при первом же переименовании.
 */
const guestFieldByContractName: Record<string, GuestField> = {
  guestName: 'name',
  guestEmail: 'email',
}

/**
 * Имя поля контракта в имя поля формы, либо `null`, если такого поля нет.
 *
 * `null`, а не само имя: подсветить поле, которого на форме нет, нечем, и молча
 * ушедшее имя выглядело бы как «проверка прошла, потому что нечего было отметить».
 */
const toGuestField = (contractName: string): GuestField | null =>
  guestFieldByContractName[contractName] ?? null

/**
 * Разбор ответа `POST /bookings`.
 *
 * Ветвление по статусу, сужение по коду — только там, где один код несёт **две
 * разные модели**: `422` это и «проверка не прошла», и «на это время записаться
 * нельзя». Свести их в один разбор значило бы отправить гостя искать негодное поле
 * интервала, которого на форме нет, и наоборот — искать несуществующее время там,
 * где виновато имя.
 *
 * `404` по коду **не** сужается: «Слот не найден» и «Тип события не найден» дают
 * один текст и одно действие, потому что различать их на записи нечем. Второй код
 * при записи и недостижим — удаления Типа нет, а идентификатор неизменен, — но
 * разбор не ветвится по нему вовсе, а не ветвится вхолостую.
 *
 * Ответов, не описанных контрактом, здесь нет: значит и отдельного текста у них
 * нет — вместо него говорится «не получилось», потому что прочие коды неизвестны
 * и выдумывать о них причину значило бы врать.
 */
export const parseCreateResponse = (
  response: bookingsCreateBookingResponse,
): CreateOutcome => {
  if (response.status === 201) {
    return { kind: 'создана' }
  }

  if (response.status === 409) {
    return { kind: 'отказ', refusal: { kind: 'занят' } }
  }

  if (response.status === 422) {
    const { data } = response

    if (data.code === 'time_not_bookable') {
      return { kind: 'отказ', refusal: { kind: 'время' } }
    }

    const fields = data.fields
      .map(toGuestField)
      .filter((field): field is GuestField => field !== null)

    return { kind: 'отказ', refusal: { kind: 'данные', fields } }
  }

  if (response.status === 404) {
    return { kind: 'отказ', refusal: { kind: 'нет такого' } }
  }

  return { kind: 'отказ', refusal: { kind: 'недоступно' } }
}

/**
 * Отказ запроса: сеть оборвалась, тела ответа не будет.
 *
 * Отдельный вид, а не подвид «недоступно», потому что последствия разные: ответ
 * сервера о недоступности означает, что запись **не** создана, а оборванный запрос
 * оставляет вопрос открытым.
 */
export const networkRefusal = (): CreateOutcome => ({
  kind: 'отказ',
  refusal: { kind: 'сеть' },
})

/**
 * Можно ли ещё раз отправить эту же форму.
 *
 * После отказа по занятости — нельзя: Слот уже чужой, и гость получил бы тот же
 * отказ по кругу, потеряв введённое имя и почту второй раз. Остальные отказы дело
 * гостя — их исправление может снова дать успех.
 */
export const canRetry = (refusal: BookingRefusal): boolean => refusal.kind !== 'занят'

/**
 * Уводит ли отказ гостя обратно к выбору дня.
 *
 * Отказ по времени — это не ошибка заполнения, а факт, что Слота больше нет:
 * гость выбирал его из сетки, а не вводил время, и подсвечивать нечего. Возврат к
 * выбору дня поэтому обязателен, а форма с устаревшим интервалом была бы формой,
 * которую нельзя отправить.
 */
export const returnsToCalendar = (refusal: BookingRefusal): boolean =>
  refusal.kind === 'время' || refusal.kind === 'нет такого'

/** Подсветка полей формы по отказу: отказ без полей не подсвечивает ничего. */
export const fieldErrorsFrom = (refusal: BookingRefusal): GuestErrors => {
  if (refusal.kind !== 'данные') {
    return {}
  }

  return refusal.fields.reduce<GuestErrors>((errors, field) => {
    errors[field] = 'Значение не подходит'
    return errors
  }, {})
}

/**
 * Текст отказа для гостя.
 *
 * Тексты занятости, времени и негодных полей различаются намеренно: один общий
 * текст сказал бы гостю неправду — например, про «выбранное время» на негодном
 * имени, которое он только что ввёл и время которого было доступно.
 *
 * У «недоступно» и «сеть» текст **один и тот же**, потому что гость не может знать,
 * где именно оборвалось: недоступность сервера и молчащая сеть неразличимы для
 * него. Различает их последствие, а не формулировка, и оно вынесено из текста в
 * `wasPossiblyCreated`.
 */
export const refusalText = (refusal: BookingRefusal): string => {
  switch (refusal.kind) {
    case 'занят':
      return 'Это время уже занял другой гость — выберите другое'
    case 'данные':
      return 'Проверьте имя и почту'
    case 'время':
      return 'Выбранное время больше недоступно'
    case 'нет такого':
      return 'Выбранное время больше недоступно'
    case 'недоступно':
    case 'сеть':
      return 'Записаться не получилось. Попробуйте ещё раз'
  }
}

/**
 * Могла ли запись создаться, несмотря на отказ.
 *
 * Только при оборванной сети: запрос ушёл, а ответа не пришло. Ответ сервера о
 * недоступности — это до отправки, там записи нет.
 */
export const wasPossiblyCreated = (refusal: BookingRefusal): boolean =>
  refusal.kind === 'сеть'