/**
 * Тексты об источниках данных — одни на всё приложение.
 *
 * Собраны здесь, а не рядом с каждым источником, по одной причине: отказ на чтении
 * звучит одинаково везде, и тексты, разложенные по страницам, разъехались бы
 * ровно там, где разъезжаются все прочие решения. Проверка одного и того же отказа
 * на странице выбора и на странице записи обязана давать одну и ту же фразу — иначе
 * гость решит, что сломалось только то место, откуда он пришёл.
 *
 * Серверное `message` сюда не попадает ни в одном виде: это строка для
 * разработчика, и на первом же отказе она оказалась бы перед гостем. Причину
 * называет контракт — код ответа, — а слова живут здесь.
 */

