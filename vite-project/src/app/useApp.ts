import { use, useEffect, useRef } from 'react'

import { AppContext, type AppContextValue } from './appContext'

/** Состояние приложения вне компонента: Брони, «сейчас» и перечитывание всего. */
export const useApp = (): AppContextValue => {
  const value = use(AppContext)

  if (value === null) {
    throw new Error('useApp вызван вне AppProvider')
  }

  return value
}

/**
 * Отдать приложению перечитывания источников страницы.
 *
 * Кнопка повтора зовёт **все** зарегистрированные, а не только одно: повтор на
 * странице перечитывал бы её один источник и правило перестало бы выполняться.
 * Гость нажал бы «Повторить» и увидел бы, что половина экрана обновилась, а
 * вторая осталась старой — без объяснения почему.
 *
 * Регистрация живёт в ссылке, а не в состоянии: перечитывания не меняются от
 * рендера к рендеру, меняется только то, что они увидят. Иначе приложение
 * перерисовывалось бы на каждом рендере страницы, ничего не меняя, а порядок
 * источников прыгал бы.
 */
export const usePageSources = (reloads: readonly (() => void)[]): void => {
  const { registerSources } = useApp()
  const latest = useRef(reloads)

  // Ссылка обновляется эффектом, а не телом рендера: правило react-hooks запрещает
  // писать в ref во время рендера, и правильно — это работа с состоянием.
  useEffect(() => {
    latest.current = reloads
  }, [reloads])

  // Регистрация переустанавливается на каждом рендере **намеренно** и стоит
  // ничего: регистрация кладёт функцию в поле провайдера, состояние не меняет и
  // перерисовку не вызывает. Зато перечитывания всегда свежие, а смена состава
  // источников подхватывается сама.
  useEffect(() => registerSources(() => latest.current.forEach((reload) => reload())))
}